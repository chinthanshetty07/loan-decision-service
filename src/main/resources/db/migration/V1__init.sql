-- Credit policies are versioned, never edited in place: a change inserts a new
-- version and deactivates the old one, so every decision can be traced back to
-- the exact rules that produced it.
create table credit_policy (
    id                   bigint generated by default as identity primary key,
    institution_code     varchar(32)   not null,
    product_type         varchar(16)   not null,
    version              int           not null,
    active               boolean       not null,
    min_credit_score     int           not null,
    refer_band           int           not null,
    max_foir             numeric(5, 4) not null,
    min_monthly_income   numeric(14, 2) not null,
    max_loan_amount      numeric(14, 2) not null,
    max_tenure_months    int           not null,
    annual_interest_rate numeric(5, 2) not null,
    created_by           varchar(64)   not null,
    created_at           timestamp with time zone not null,
    constraint uq_policy_version unique (institution_code, product_type, version)
);

create table loan_application (
    id               uuid primary key,
    idempotency_key  varchar(64) unique,
    institution_code varchar(32)    not null,
    product_type     varchar(16)    not null,
    applicant_name   varchar(120)   not null,
    pan_masked       varchar(10)    not null,
    pan_hash         varchar(64)    not null,
    monthly_income   numeric(14, 2) not null,
    existing_emi     numeric(14, 2) not null,
    requested_amount numeric(14, 2) not null,
    tenure_months    int            not null,
    status           varchar(24)    not null,
    credit_score     int,
    proposed_emi     numeric(14, 2),
    foir             numeric(6, 4),
    policy_id        bigint references credit_policy (id),
    decision_reasons varchar(1000),
    created_by       varchar(64)    not null,
    created_at       timestamp with time zone not null,
    decided_at       timestamp with time zone
);

create table audit_event (
    id             bigint generated by default as identity primary key,
    application_id uuid          not null references loan_application (id),
    event_type     varchar(48)   not null,
    actor          varchar(64)   not null,
    detail         varchar(2000),
    created_at     timestamp with time zone not null
);

create index idx_audit_application on audit_event (application_id);
create index idx_application_institution on loan_application (institution_code, created_at);

